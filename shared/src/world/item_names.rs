#[cfg(test)]
mod tests {
    use super::*;
    use crate::world::ItemId;

    #[test]
    fn the_legacy_item_names_never_change() {
        // the names joined by spaces, hashed by FNV-1a
        let joined = LEGACY_ITEM_NAMES.join(" ");
        let hash = joined
            .bytes()
            .fold(0xcbf2_9ce4_8422_2325_u64, |hash, byte| {
                (hash ^ u64::from(byte)).wrapping_mul(0x0100_0000_01b3)
            });
        assert_eq!(LEGACY_ITEM_NAMES.len(), 519);
        assert_eq!(
            hash, 0x4088_e29a_d6bc_09cc,
            "the legacy list of item names changed: the items of the \
            worlds saved without a list of their own would turn into other items"
        );
    }

    #[test]
    fn the_engine_items_are_numbered_as_the_legacy_names() {
        for (place, id) in ItemId::ENGINE.into_iter().enumerate() {
            assert_eq!(LEGACY_ITEM_NAMES[place], id.name());
        }
    }
}

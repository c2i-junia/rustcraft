//! The plans of the dungeons, written as layers of characters like the pieces of the villages:
//! seen from above with the door toward `-Z`, each layer a list of rows from the front, from the
//! lowest layer up.

use bevy::prelude::*;
use shared::world::{BlockDirection, BlockId, MobKind};

use super::DungeonKind;

/// What a character of a layer stands for.
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum Cell {
    /// What is there is left.
    Leave,
    Air,
    /// Air, where a hostile of the dungeon appears.
    Guard(MobKind),
    /// Worn stone, see `masonry`.
    Masonry,
    /// Worn stone that only stands as high as what is left of its column.
    Ruined,
    /// The broken paving of a courtyard.
    Paving,
    Block(BlockId, BlockDirection),
}

/// The cell a character stands for.
fn cell(c: char) -> Cell {
    use BlockDirection::*;
    let block = |id| Cell::Block(id, Front);
    match c {
        ' ' => Cell::Leave,
        '.' => Cell::Air,
        'W' => Cell::Masonry,
        '#' => Cell::Ruined,
        '%' => Cell::Paving,
        'b' => Cell::Guard(MobKind::Bramble),
        'g' => Cell::Guard(MobKind::Gnawer),
        'r' => Cell::Guard(MobKind::Roller),
        'c' => Cell::Guard(MobKind::Cinderling),
        'h' => block(BlockId::HewnStone),
        'l' => block(BlockId::HewnStoneSlab),
        'S' => block(BlockId::Slate),
        'P' => block(BlockId::Limestone),
        'B' => block(BlockId::BrickWall),
        'O' => block(BlockId::Obsidian),
        'I' => block(BlockId::BronzeBlock),
        'D' => block(BlockId::GoldBlock),
        'N' => block(BlockId::Grass),
        't' => block(BlockId::TallGrass),
        'C' => block(BlockId::Chest),
        'A' => block(BlockId::Barrel),
        'L' => block(BlockId::Lantern),
        'u' => block(BlockId::UnlitCampfire),
        '~' => block(BlockId::Lava),
        // a ladder against the wall behind it
        'X' => Cell::Block(BlockId::Ladder, Back),
        _ => panic!("no cell for {c:?}"),
    }
}

type Layers = &'static [&'static [&'static str]];

/// A dungeon, as layers of characters (see the module).
pub struct Blueprint {
    /// The height of the first layer above the floor of the door.
    pub lowest: i32,
    /// The column of the front row the door is in.
    pub door: i32,
    pub layers: Layers,
}

impl Blueprint {
    pub fn of(kind: DungeonKind) -> &'static Blueprint {
        match kind {
            DungeonKind::Ruin => &RUIN,
            DungeonKind::Crypt => &CRYPT,
            DungeonKind::Sanctuary => &SANCTUARY,
        }
    }

    /// Width along x and depth along z.
    pub fn size(&self) -> (i32, i32) {
        let layer = self.layers[0];
        (layer[0].len() as i32, layer.len() as i32)
    }

    /// Its cells, by their position from the first column of the lowest layer.
    pub fn cells(&self) -> impl Iterator<Item = (IVec3, Cell)> {
        self.layers.iter().enumerate().flat_map(|(y, layer)| {
            layer.iter().enumerate().flat_map(move |(z, row)| {
                row.chars()
                    .enumerate()
                    .map(move |(x, c)| (IVec3::new(x as i32, y as i32, z as i32), cell(c)))
            })
        })
    }
}


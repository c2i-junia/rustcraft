def draw(name, art):
    rows = art.strip("\n").split("\n")
    assert len(rows) == 16 and all(len(row) == 16 for row in rows), name
    clear = bytes(4)
    pixel = lambda key: bytes.fromhex(PALETTE[key][1:]) + b"\xff"
    write(
        ITEMS / f"{name}.png",
        16,
        [clear if key == "." else pixel(key) for row in rows for key in row],
    )


